    print('--- Generation test ---')
    seed = torch.randint(0, 256, (256,)).to(device)  # 2 windows worth
    gen = m.generate_from_stream(seed, max_new=64, temp=0.8)
    assert gen.shape[0] == 64, f'Expected 64 tokens, got {gen.shape[0]}'
    print(f'  Generation OK: {gen.shape}, tokens: {gen[:16].tolist()}...')

